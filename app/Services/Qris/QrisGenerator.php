<?php

namespace App\Services\Qris;

use App\Models\Invoice;
use App\Models\PaymentGateway;
use App\Models\QrisCode;
use Illuminate\Support\Facades\Storage;
use Illuminate\Support\Str;

/**
 * QRIS dynamic per invoice. For demo / no-provider mode, generates a static QR
 * with payload encoding amount + invoice ref. For production, integrate provider
 * (Midtrans/iPaymu/Mekari/etc) via PaymentGateway adapter.
 */
class QrisGenerator
{
    public function generate(Invoice $invoice, ?PaymentGateway $provider = null, int $expiresMinutes = 30): QrisCode
    {
        // Cancel any existing active QR for this invoice
        QrisCode::where('invoice_id', $invoice->id)
            ->where('status', 'active')
            ->update(['status' => 'cancelled']);

        $payload = $this->buildPayload($invoice, $provider);
        $imagePath = $this->renderQrImage($payload, $invoice->id);

        return QrisCode::create([
            'workspace_id'  => $invoice->workspace_id,
            'invoice_id'    => $invoice->id,
            'provider_id'   => $provider?->id,
            'amount'        => $invoice->balance_due ?? $invoice->total,
            'qr_payload'    => $payload,
            'qr_image_path' => $imagePath,
            'expires_at'    => now()->addMinutes($expiresMinutes),
            'status'        => 'active',
        ]);
    }

    /**
     * Build EMV-compatible QRIS payload string.
     * For real integration, this is generated by provider API.
     */
    private function buildPayload(Invoice $invoice, ?PaymentGateway $provider): string
    {
        $merchantName = $invoice->workspace?->name ?? 'Invocely';
        $amount = number_format((float) ($invoice->balance_due ?? $invoice->total), 2, '.', '');
        $reference = $invoice->invoice_no;

        // Simplified QRIS payload structure (real QRIS requires NMID + MPM cert)
        // This format works for demo/scanner test; production: use provider response
        return sprintf(
            '00020101021226660014ID.CO.QRIS.WWW0118%s5204481253033605802ID59%02d%s60%02d%s62%02d%s6304XXXX',
            substr(str_pad($invoice->id, 12, '0', STR_PAD_LEFT), 0, 18),
            min(25, strlen($merchantName)),
            substr($merchantName, 0, 25),
            min(15, strlen('JAKARTA')),
            'JAKARTA',
            min(20, strlen($reference)),
            substr($reference, 0, 20),
        );
    }

    private function renderQrImage(string $payload, int $invoiceId): string
    {
        $writer = new \BaconQrCode\Writer(new \BaconQrCode\Renderer\ImageRenderer(
            new \BaconQrCode\Renderer\RendererStyle\RendererStyle(400),
            new \BaconQrCode\Renderer\Image\SvgImageBackEnd()
        ));

        $svg = $writer->writeString($payload);
        $filename = "qris/{$invoiceId}/" . Str::random(16) . '.svg';
        Storage::disk('public')->put($filename, $svg);

        return $filename;
    }

    public function markAsPaid(QrisCode $qris, ?string $providerRef = null): void
    {
        $qris->update([
            'status'      => 'paid',
            'paid_at'     => now(),
            'provider_ref' => $providerRef,
        ]);
    }
}
